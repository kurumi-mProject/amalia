package com.my.amali.data.ai

import android.content.Context
import com.konovalov.vad.silero.Vad
import com.konovalov.vad.silero.VadSilero
import com.konovalov.vad.silero.config.FrameSize
import com.konovalov.vad.silero.config.Mode
import com.konovalov.vad.silero.config.SampleRate
import kotlin.math.sqrt

/**
 * Детектор голосовой активности: отличает речь от тишины и шума.
 *
 * ## Зачем он нужен именно теперь
 *
 * Раньше границу фразы определял сервер: Deepgram присылал `speech_final`
 * после собственного endpointing. Это работало, но означало, что каждое
 * решение о конце фразы стоит сетевого раунда — и, что важнее, требует
 * открытого веб-сокета на всё время разговора. Любая просадка связи
 * превращалась в «первые 200 мс фразы улетели в никуда».
 *
 * Теперь распознавание — обычный HTTP-запрос с нарезкой аудио, а значит
 * решение «человек договорил» обязано приниматься локально и мгновенно.
 * Так и делает VAD: он читает те же 20 мс аудио, что уже сняты с микрофона,
 * и отвечает «речь / не речь» за единицы миллисекунд, не трогая сеть.
 *
 * ## Две реализации, один контракт
 *
 * [Silero] — нейросетевая модель (ONNX, ~2 МБ) внутри приложения. Она
 * различает речь и фоновый шум по спектру, а не по громкости, поэтому
 * работает в машине, в кафе и на улице одинаково: шум не «зажигает»
 * детектор, а тихая речь — не гаснет.
 *
 * [Energy] — арифметический запасной вариант на RMS. Он включается, только
 * если модель не загрузилась (например, устройство без поддержки нужной
 * версии ONNX). Работать он хуже, но лучше, чем не работать вовсе: без
 * VAD приложение вообще не смогло бы определить конец фразы.
 *
 * Контракт намеренно узкий: одна функция, один вопрос — «это речь?».
 * Все пороги, счётчики тишины и логика конца фразы живут выше, в
 * [GroqWhisperStt], потому что относятся к записи, а не к детекции.
 */
interface VoiceActivityDetector {

    /**
     * Классифицирует один кадр.
     *
     * @param frame PCM 16-bit mono, ровно [frameSamples] сэмплов.
     * @return true, если в кадре человеческая речь.
     */
    fun isSpeech(frame: ShortArray): Boolean

    /**
     * Размер кадра, который обязана принимать реализация.
     *
     * Silero обучена на конкретных длинах окна (256 или 512 сэмплов при
     * 16 кГц), поэтому это не «рекомендация», а требование модели.
     */
    val frameSamples: Int

    /** Освобождает нативные ресурсы (у Silero — сессию ONNX). */
    fun close()

    companion object {
        /**
         * Частота дискретизации всего конвейера распознавания.
         *
         * 16 кГц — требование и Silero, и Whisper. Держать её в одном месте
         * важно: микрофон, VAD, нарезка WAV и HTTP-запрос обязаны совпадать,
         * иначе Whisper получит звук с неверной скоростью и «услышит» тарабарщину.
         */
        const val SAMPLE_RATE = 16_000

        /**
         * Длина кадра для VAD: 512 сэмплов = 32 мс при 16 кГц.
         *
         * Именно это окно Silero считает «нативным»: модель принимает его
         * без внутренней пересборки тензора. 256 сэмплов (16 мс) дали бы
         * более точное позиционирование границы, но вдвое больше вызовов
         * сети ONNX на секунду записи — на телефоне это заметная батарея
         * без выигрыша в качестве.
         */
        const val FRAME_SAMPLES = 512

        /**
         * Длительность кадра в миллисекундах — для расчётов порогов тишины.
         *
         * Вычисляется из частоты дискретизации и размера окна, а не вписана
         * числом: если когда-нибудь окно изменится (например, на 256 сэмплов
         * ради более точной границы), производные пороги поедут вместе с ним
         * и не придётся искать по коду захардкоженную «32».
         */
        const val FRAME_MS = FRAME_SAMPLES * 1000 / SAMPLE_RATE

        /**
         * Создаёт Silero VAD, а при неудаче — RMS-запасной вариант.
         *
         * Модель загружается синхронно (десятки миллисекунд), поэтому вызов
         * делается из фоновой корутины. Исключение не пробрасывается: голосовой
         * ассистент обязан остаться работоспособным даже там, где ONNX не
         * поднялся.
         */
        fun create(context: Context, aggressive: Boolean = true): VoiceActivityDetector {
            val silero = runCatching { Silero(context, aggressive) }.getOrNull()
            return silero ?: Energy()
        }
    }
}

/**
 * Silero VAD — нейросетевой детектор речи из библиотеки `android-vad`.
 *
 * ## Почему режим агрессивный
 *
 * [Mode.VERY_AGGRESSIVE] поднимает порог срабатывания: детектор перестаёт
 * считать речью шорохи, музыку и чужой разговор за стеной. Для диктовки это
 * было бы вредно (модель «проглатывала» бы тихие слова), но ассистенту нужна
 * обратная ошибка: лучше принять тихое слово за шум и не отправить лишний
 * запрос, чем ловить конец фразы бесконечно, потому что в комнате играет
 * музыка.
 *
 * ## Окно сглаживания
 *
 * Библиотека считает речь «состоявшейся» только после [SPEECH_WINDOW_MS]
 * подряд распознанных кадров (и тишину — после [SILENCE_WINDOW_MS]). Это
 * встроенный гистерезис: без него одиночный щелчок мыши открывал бы
 * сегмент речи, а случайная пауза между словами — закрывала.
 *
 * Значение по умолчанию (95 мс) для нас слишком велико: пользователь
 * начинает говорить, а первые ~100 мс речи VAD ещё считает тишиной, и
 * начало слова «включи» превращается в «ключи». Поэтому окно уменьшено
 * до минимально допустимого библиотекой — оно всё ещё гасит щелчки, но не
 * съедает начало фразы.
 */
private class Silero(
    context: Context,
    aggressive: Boolean,
) : VoiceActivityDetector {

    private val model: VadSilero = Vad.builder()
        .setContext(context)
        .setSampleRate(SampleRate.SAMPLE_RATE_16K)
        .setFrameSize(FrameSize.FRAME_SIZE_512)
        .setMode(if (aggressive) Mode.VERY_AGGRESSIVE else Mode.NORMAL)
        .setSpeechDurationMs(SPEECH_WINDOW_MS)
        .setSilenceDurationMs(SILENCE_WINDOW_MS)
        .build()

    override val frameSamples: Int = VoiceActivityDetector.FRAME_SAMPLES

    override fun isSpeech(frame: ShortArray): Boolean = model.isSpeech(frame)

    override fun close() {
        runCatching { model.close() }
    }

    private companion object {
        /**
         * Сколько кадров подряд должны быть речью, чтобы детектор поверил.
         *
         * Минимум, который принимает библиотека. Кадр длится 32 мс, значит
         * окно ≈ 95 мс — это ровно тот запас, который перекрывает дрожание
         * начала слова, но не слышен пользователю.
         */
        const val SPEECH_WINDOW_MS = 95

        /** Сколько кадров тишины считаются паузой; закрывает шумовые «провалы». */
        const val SILENCE_WINDOW_MS = 95
    }
}

/**
 * Запасной детектор на среднеквадратичной громкости.
 *
 * Он не понимает, что именно звучит, — только «громко / тихо». Поэтому
 * включается лишь тогда, когда нейросеть недоступна: молчащее приложение
 * хуже, чем приложение, которое иногда путает речь с громким шумом.
 *
 * Порог намеренно высокий: лучше пропустить тихое слово в начале, чем
 * открыть сегмент речи от гула улицы и тянуть его до жёсткого лимита.
 */
private class Energy : VoiceActivityDetector {

    override val frameSamples: Int = VoiceActivityDetector.FRAME_SAMPLES

    override fun isSpeech(frame: ShortArray): Boolean {
        if (frame.isEmpty()) return false
        var sum = 0.0
        for (sample in frame) {
            val value = sample.toDouble()
            sum += value * value
        }
        val rms = sqrt(sum / frame.size)
        return rms >= RMS_THRESHOLD
    }

    override fun close() = Unit

    private companion object {
        /**
         * Порог 750 из диапазона int16 (≈2.3% от полной шкалы).
         *
         * На живом микрофоне телефона обычная речь в 20 см даёт RMS
         * 2000–6000, то есть заметно выше порога, а шум комнаты — 100–400.
         * Значение по центру этого разрыва и выбрано.
         */
        const val RMS_THRESHOLD = 750.0
    }
}
