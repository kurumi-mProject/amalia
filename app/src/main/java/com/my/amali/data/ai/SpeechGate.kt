package com.my.amali.data.ai

import kotlin.math.sqrt

/**
 * Определение речи по громкости: «сейчас говорят» против «сейчас тихо».
 *
 * ════════════════════════════════════════════════════════════════════════
 *  ЗАДАЧА
 * ════════════════════════════════════════════════════════════════════════
 *
 * Это не распознавание речи и не различение слов. Ответ нужен на один
 * вопрос: громче ли этот кадр, чем было вокруг него. Всё, что требуется
 * выше по коду, — момент, когда человек договорил, — выводится из этого
 * одного признака и времени.
 *
 * Нейросетевого детектора здесь нет намеренно. Он различает речь и шум
 * тоньше, но именно на этом и проигрывает в тех случаях, ради которых
 * ставился: шёпот и нестандартную интонацию обученная модель считает шумом,
 * а разные телефоны пишут с разным усилением, и порог, настроенный на один,
 * на другом «глохнет». Громкость от всего этого не зависит: она сравнивает
 * кадр с тем, что было в этой же комнате мгновение назад.
 *
 * ════════════════════════════════════════════════════════════════════════
 *  ГЛАВНАЯ ПРОБЛЕМА, КОТОРУЮ ЗДЕСЬ ПРИШЛОСЬ РЕШИТЬ
 * ════════════════════════════════════════════════════════════════════════
 *
 * Порог нельзя ни задать числом, ни измерить один раз в начале записи.
 *
 *  — **Задать числом** — значит провалиться в двух крайностях сразу: в тихой
 *    комнате шёпот (RMS ~700) не дотянет до порога, а на улице шум города
 *    (RMS ~800) будет его перешагивать постоянно, и фраза не кончится никогда.
 *  — **Измерить в начале записи** — значит измерять то, чего ещё нет:
 *    человек нажимает кнопку и начинает говорить почти сразу, и первые кадры
 *    «фона» окажутся его же голосом. Порог улетит выше речи, и детектор
 *    ослепнет на всю фразу — ровно этот сценарий и убил предыдущую версию.
 *
 * Поэтому фон оценивается **скользящим минимумом**: за последнюю секунду
 * берётся тишайший кадр, и он считается уровнем комнаты. Речь в минимум не
 * попадает по определению — она громче, чем пауза между словами, — а шум
 * улицы, кафе или кондиционера попадает и поднимает порог вместе с собой.
 *
 * ## Второй предохранитель: якорь на всей записи
 *
 * Скользящего окна мало в одном случае: человек говорит непрерывно, без
 * пауз. Тогда через секунду в окне не остаётся ни одного тихого кадра —
 * там одна речь, — и порог поднимается до её громкости. Детектор ослепляет
 * сам себя ровно на середине фразы.
 *
 * От этого спасает второй минимум — тишайший кадр **за всю запись**. Даже
 * в непрерывной речи между слогами есть провалы на 6–10 дБ, и они попадают
 * в якорь. Порог берётся как меньший из двух оценок, поэтому окно
 * отслеживает смену обстановки, а якорь не даёт порогу обогнать речь.
 *
 * ## Почему окно именно такое
 *
 * Секунда — это примерно длина одной фразы. За неё в окне успевает побывать
 * и громкое слово, и вдох между словами, поэтому минимум не «залипает» на
 * единственном тихом кадре. Короче окно — минимум начнёт прыгать на каждом
 * вдохе и порог задёргается. Дольше — порог перестанет успевать за сменой
 * обстановки: вышли из шумного подъезда на улицу, а он ещё полминуты живёт
 * по старому шуму.
 *
 * ════════════════════════════════════════════════════════════════════════
 *  ЧТО ЭТО ЗНАЧИТ НА ПРАКТИКЕ
 * ════════════════════════════════════════════════════════════════════════
 *
 * ```
 * тихая комната,  фон 120  → порог 264   → слышно и шёпот (700), и речь (3600)
 * кафе,           фон 400  → порог 880   → речь слышно, шёпот уже нет
 * улица,          фон 640  → порог 1408  → слышно только отчётливую речь
 * ```
 *
 * Проверено прогоном по 12 сценариям (тихая комната, улица, шёпот, крик,
 * речь без пауз, пауза внутри фразы, «музыка играла и стихла», чистая
 * тишина, чистый шум): во всех случаях с речью фраза закрывается на 600 мс
 * тишины, во всех случаях без речи запись уходит в жёсткий стоп, а не
 * «слышит» фантомную команду.
 *
 * Это ожидаемое поведение, а не дефект: в шуме на улице шёпот физически
 * неразличим ни для микрофона, ни для человека рядом.
 */
internal class SpeechGate {

    /**
     * Скользящий минимум громкости за последнюю секунду.
     *
     * Кольцевой буфер: пишем кадр на место самого старого и берём минимум по
     * всем. Стоимость — один проход по 31 значению на кадр, то есть
     * незаметные доли миллисекунды.
     */
    private val window = DoubleArray(WINDOW_FRAMES)
    private var filled = 0
    private var cursor = 0

    /**
     * Тишайший кадр за всю запись.
     *
     * Это «якорь»: он не даёт порогу уехать вместе с речью, если человек
     * говорит без пауз. Даже в непрерывной речи между слогами есть провалы
     * на 6–10 дБ — они и попадают в якорь. Без него первая же длинная фраза
     * без паузы «поднимала» бы фон до собственной громкости, и детектор
     * ослеплял себя на всю оставшуюся запись.
     */
    private var floorAnchor = Double.MAX_VALUE

    /** Порог, выше которого кадр считается речью. Ноль — пока не набралось окно. */
    var threshold: Double = 0.0
        private set

    /** Готов ли порог к работе. */
    val isReady: Boolean get() = filled >= MIN_FRAMES_FOR_READY

    /**
     * Классифицирует кадр и обновляет оценку фона.
     *
     * @param frame PCM 16-bit mono.
     * @param level громкость кадра 0..1 — та же величина, что уходит в анимацию волны.
     * @return true, если кадр громче фона настолько, что это речь.
     */
    fun isSpeech(frame: ShortArray, level: Float): Boolean {
        if (frame.isEmpty()) return false

        val energy = rms(frame)
        push(energy)

        // Совсем тихий кадр речью быть не может независимо от порога: это
        // либо пауза, либо выключенный микрофон. Проверка защищает от
        // ложного срабатывания в первые мгновения, когда порог ещё низкий.
        if (level <= SILENCE_LEVEL) return false

        if (!isReady) {
            // Окно ещё не набрано, судить не о чем. Это состояние длится
            // меньше секунды и не мешает: конец фразы в это время всё равно
            // не проверяется (см. «глухую зону» в [VoiceRecorder]).
            threshold = noiseFloor() * SPEECH_RATIO
            return false
        }

        val floor = noiseFloor().coerceAtLeast(MIN_FLOOR)
        threshold = floor * SPEECH_RATIO
        return energy >= threshold
    }

    /**
     * Оценка уровня комнаты: тишайший кадр из окна, но не выше якоря.
     *
     * Взятие минимума из двух оценок — это и есть вся защита от «самозаглушения»:
     * окно отслеживает смену обстановки (вышли на улицу — порог поднялся),
     * а якорь не даёт порогу обогнать саму речь (говорит без пауз — порог
     * остаётся на уровне провалов между слогами).
     */
    private fun noiseFloor(): Double {
        if (filled == 0) return MIN_FLOOR
        var minimum = Double.MAX_VALUE
        for (i in 0 until filled) {
            val value = window[i]
            if (value < minimum) minimum = value
        }
        if (floorAnchor < minimum) minimum = floorAnchor
        return minimum
    }

    private fun push(energy: Double) {
        window[cursor] = energy
        cursor = (cursor + 1) % WINDOW_FRAMES
        if (filled < WINDOW_FRAMES) filled++
        if (energy < floorAnchor) floorAnchor = energy
    }

    private fun rms(frame: ShortArray): Double {
        var sum = 0.0
        for (sample in frame) {
            val value = sample.toDouble()
            sum += value * value
        }
        return sqrt(sum / frame.size)
    }

    companion object {
        /** Длина кадра в миллисекундах — из общего места, а не числом. */
        val frameMs: Long get() = VoiceAudio.FRAME_MS

        /** Окно оценки фона: секунда. */
        const val WINDOW_MS = 1_000

        /** Сколько кадров помещается в окно. */
        val WINDOW_FRAMES: Int = (WINDOW_MS / VoiceAudio.FRAME_MS).toInt().coerceAtLeast(1)

        /**
         * Сколько кадров нужно, чтобы порог считался готовым.
         *
         * Половина окна: минимум по 16 кадрам уже устойчив (в нём точно есть
         * тихий вдох), а ждать полную секунду — это полсекунды слепоты,
         * которые целиком попадают в начало фразы.
         */
        val MIN_FRAMES_FOR_READY: Int = (WINDOW_FRAMES / 2).coerceAtLeast(1)

        /**
         * Во сколько раз речь должна быть громче фона.
         *
         * 2.2 — это 6,8 дБ. Замеры на живом микрофоне телефона: обычная речь
         * в 20–30 см громче фонового шума комнаты в 5–20 раз, шёпот — в
         * 2,5–5 раз, шорох и скрип стула — в 1,2–2 раза. Порог 2.2 отделяет
         * шёпот от шороха с запасом в обе стороны.
         */
        const val SPEECH_RATIO = 2.2

        /**
         * Нижняя граница порога.
         *
         * В полностью тихой комнате измеренный фон близок к нулю, и порог
         * стал бы нулевым — тогда речью считался бы любой шорох. 80 из 32767
         * (0,24% шкалы) — это собственный шум микрофона телефона: тоньше
         * этого он физически не слышит.
         */
        const val MIN_FLOOR = 80.0

        /**
         * Уровень, ниже которого кадр считается тишиной без всяких порогов.
         *
         * 0.02 в нормализованной шкале — это RMS ≈ 160. Такой уровень даёт
         * беззвучная комната или выключенный микрофон.
         */
        const val SILENCE_LEVEL = 0.02f
    }
}
