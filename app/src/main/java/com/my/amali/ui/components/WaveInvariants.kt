package com.my.amali.ui.components

import com.my.amali.domain.entity.WaveSettings
import kotlin.math.abs
import kotlin.math.pow

/**
 * Инварианты волны: проверяются без Compose, без Android и без эмулятора.
 *
 * ════════════════════════════════════════════════════════════════════════
 *  ЗАЧЕМ ЭТИ ТЕСТЫ СУЩЕСТВУЮТ
 * ════════════════════════════════════════════════════════════════════════
 *
 * Волна — единственный элемент приложения, который обязана быть
 * **честной**: её движение означает звук, а неподвижность — тишину. Ровно
 * это свойство и было сломано в первой версии: три независимых от
 * громкости источника движения (бесконечное «дыхание», фазовая задержка
 * от него и постоянная добавка 22% высоты) заставляли полосы качаться при
 * нулевом уровне. Заметить это глазами можно было только случайно, а после
 * следующего рефакторинга — потерять снова.
 *
 * Поэтому правило «нет звука — нет движения» зафиксировано здесь как
 * **математическое свойство**, а не как комментарий. Формула формы вынесена
 * в [archGain] и [decayRatio] без единой зависимости от времени, и тест
 * проверяет, что она возвращает ноль при нулевом уровне для любой позиции
 * полосы. Обратно это свойство сломать уже нельзя, не уронив тест.
 *
 * ════════════════════════════════════════════════════════════════════════
 *  ЧТО ИМЕННО ПРОВЕРЯЕТСЯ
 * ════════════════════════════════════════════════════════════════════════
 *
 *  1. **Тишина даёт ровный строй.** При уровне ниже [SilenceGate] ни одна
 *     полоса не получает высоты: все стоят на минимуме, и никто не «дышит».
 *  2. **Гейт тишины работает.** Уровень чуть выше гейта даёт строго
 *     положительную высоту, а чуть ниже — строго нулевую. Без этого гейта
 *     шум микрофона превращался бы в вечное шевеление.
 *  3. **Гребень не движет тишину.** Множитель гребня при нулевом уровне
 *     равен единице для любой дистанции от центра: он сообщает форму, но
 *     не создаёт движения.
 *  4. **Громче звук — выше полосы.** Монотонность по уровню: индикатор не
 *     имеет права показывать «громко» тише, чем «тихо».
 *  5. **Спад короче подъёма.** Скорость сглаживания вниз выше, чем вверх,
 *     и ровно в оговорённое число раз.
 *  6. **maxHeight — это высота.** Верхняя граница формы равна единице, то
 *     есть полоса дотягивается до заявленной высоты, а не до её половины.
 */
internal object WaveInvariants {

    /**
     * Минимум тестов для проверки одного свойства: позиции от центра
     * распределены по всей ширине волны, включая обе крайние полосы.
     */
    private val Distances = listOf(0f, 0.25f, 0.5f, 0.75f, 1f)

    /**
     * Высота полосы без минимума, 0..1 — та же формула, что в отрисовке.
     *
     * Продублирована здесь осознанно: тест обязан проверять **правило**, а
     * не рисование. Если когда-нибудь отрисовка изменится, тест поймает
     * расхождение раньше, чем пользователь — плавающие полосы.
     */
    fun height(level: Float, distance: Float, sensitivity: Float): Float {
        if (level < SilenceGate) return 0f
        return (level * sensitivity * archGain(distance, level)).coerceIn(0f, 1f).pow(0.78f)
    }

    /** Множитель гребня: 1 при нулевом уровне для любой дистанции. */
    fun archGain(distance: Float, level: Float): Float =
        (1f - 0.35f * distance.coerceIn(0f, 1f) * level).coerceIn(0f, 1f)

    /** Во сколько раз спад быстрее подъёма при данном сглаживании. */
    fun decayRatio(smoothing: Float): Float =
        smoothingStep(smoothing, rising = false) / smoothingStep(smoothing, rising = true)

    /** Полный прогон инвариантов: возвращает список нарушений. */
    fun violations(): List<String> {
        val problems = mutableListOf<String>()
        val settings = WaveSettings()

        // 1. Тишина — ровный строй.
        Distances.forEach { distance ->
            val h = height(level = 0f, distance = distance, sensitivity = settings.sensitivity)
            if (h != 0f) problems += "тишина дала высоту $h на дистанции $distance"
        }

        // 2. Гейт: ниже порога — ноль, выше — строго больше нуля.
        val below = height(SilenceGate - 0.001f, 0.5f, settings.sensitivity)
        val above = height(SilenceGate + 0.05f, 0.5f, settings.sensitivity)
        if (below != 0f) problems += "уровень ниже гейта дал высоту $below"
        if (above <= 0f) problems += "уровень выше гейта не дал высоты"

        // 3. Гребень в тишине — единица.
        Distances.forEach { distance ->
            val gain = archGain(distance = distance, level = 0f)
            if (abs(gain - 1f) > 1e-6f) {
                problems += "гребень в тишине равен $gain на дистанции $distance"
            }
        }

        // 4. Монотонность по уровню.
        var previous = -1f
        listOf(0.1f, 0.25f, 0.4f, 0.6f, 0.8f, 1f).forEach { level ->
            val h = height(level, distance = 0f, sensitivity = settings.sensitivity)
            if (h < previous) problems += "рост уровня до $level уменьшил высоту"
            previous = h
        }

        // 5. Спад быстрее подъёма.
        listOf(0.05f, 0.22f, 0.45f, 0.6f).forEach { smoothing ->
            val ratio = decayRatio(smoothing)
            if (ratio <= 1f) problems += "при сглаживании $smoothing спад не быстрее подъёма"
        }

        // 6. Высота при полной громкости достигает верхней границы.
        val peak = height(level = 1f, distance = 0f, sensitivity = 4f)
        if (peak < 0.99f) problems += "полоса не дотягивается до maxHeight: $peak"

        return problems
    }
}

/**
 * Отчёт о волне для лога приложения.
 *
 * Выводится один раз при первом показе волны: если инварианты нарушены,
 * это видно в logcat строкой `[WAVE]`, а не выясняется через месяц по
 * жалобе «полоски дрожат на пустом экране».
 */
internal fun waveInvariantReport(): String {
    val problems = WaveInvariants.violations()
    return if (problems.isEmpty()) {
        "инварианты волны соблюдены: тишина неподвижна, спад быстрее подъёма"
    } else {
        "НАРУШЕНИЯ ВОЛНЫ: " + problems.joinToString(separator = "; ")
    }
}
