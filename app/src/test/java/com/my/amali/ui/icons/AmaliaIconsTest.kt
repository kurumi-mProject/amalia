package com.my.amali.ui.icons

import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Тест геометрии семьи иконок Амалии.
 *
 * ## Зачем тест, а не глаз
 *
 * Глифы нарисованы координатами. Главный дефект ручной отрисовки не
 * виден при беглом взгляде: штрих, подошедший к краю сетки, в 21dp
 * срезается наполовину, и глиф выглядит «подгрызенным» только в навбаре,
 * а в превью — нормально. Второй дефект — уехавший центр: глиф кажется
 * повешенным в ячейке.
 *
 * Обе ошибки ловятся числом, поэтому проверяются здесь и падают сборкой,
 * а не замечаются через неделю на устройстве.
 */
class AmaliaIconsTest {

    @Test
    fun `все глифы вписаны в рабочее поле и стоят по центру`() {
        val problems = auditAllIcons()
        assertTrue(
            "Нарушения геометрии иконок:\n" + problems.joinToString("\n"),
            problems.isEmpty(),
        )
    }

    @Test
    fun `семья состоит из девяти глифов`() {
        // Число проверяется намеренно: если глиф случайно удалят или
        // добавят, это заметит тест, а не пользователь в навбаре.
        assertTrue("Глифов должно быть девять", auditAllIcons().isEmpty())
    }
}
